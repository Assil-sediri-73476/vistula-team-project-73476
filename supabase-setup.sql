-- Run once in a NEW, separate Supabase demonstration project.
-- Contains public test data only. Every visitor may read and modify these tasks.
begin;
create table public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  description text,
  completed boolean not null default false
);
alter table public.tasks enable row level security;
grant usage on schema public to anon;
grant select, insert, update, delete on public.tasks to anon;
grant usage, select on sequence public.tasks_id_seq to anon;
create policy "Public demo tasks read" on public.tasks for select to anon using (true);
create policy "Public demo tasks create" on public.tasks for insert to anon with check (true);
create policy "Public demo tasks update" on public.tasks for update to anon using (true) with check (true);
create policy "Public demo tasks delete" on public.tasks for delete to anon using (true);
commit;
